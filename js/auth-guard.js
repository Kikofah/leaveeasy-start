// ─────────────────────────────────────────────────────────────
// js/auth-guard.js — กันหน้านี้ไว้ให้เฉพาะคนที่ล็อกอินแล้วเท่านั้น
// ต้องโหลดหลัง js/firebase-init.js เสมอ
// ─────────────────────────────────────────────────────────────

firebase.auth().onAuthStateChanged(function (ผู้ใช้) {
  if (!ผู้ใช้) {
    location.href = "login.html";
  }
});
